"""Original published-F32 viscosity operator on80native-qualified patterns.

All neural forwards execute onCUDA. CPUwork decodes retained data/scoresfields;
the originalCPUprobe is read only,never regenerated by a CPUmodel.
"""
import argparse
import hashlib
import importlib.util
import os
from pathlib import Path
import resource
import statistics
import sys
import time

from import_common_generator_measurements import ROOT,RUN,read,save,binding,require
from component_material import current_publication,observed_file,selected_inventory
from cuda_forward_observer import CUDAForwardObserver
from pressure_portfolio_gpu_timing import resources


def verify_sources(protocol):
    for name,expected in protocol['source_sha256'].items():
        require(hashlib.sha256((ROOT/name).read_bytes()).hexdigest() == expected,'Frozen component source changed: '+name)


def digest(array):
    return hashlib.sha256(array.tobytes()).hexdigest()


def run(protocol_path,phase):
    current_publication(ROOT)
    protocol = read(protocol_path)
    require(protocol['schema'] == 'rheon.viscosity-component-GPU-benchmark.v1' and phase in (0,1)
            and os.environ.get('TULDOK_TORCH_DEVICE') == 'cuda','Explicit CUDA component protocol required')
    verify_sources(protocol)
    require(binding(ROOT/protocol['material']['path']) == protocol['material'],'Original20component material changed')
    material = read(ROOT/protocol['material']['path'])
    entry = next(row for row in material['models'] if row['fit_item_id'] == protocol['fit_item_id'])
    require(entry['task'] == 'viscosity_component' and entry['parameter_dtypes'] == ['<f4']
            and entry['serialized_tensor_elements'] == 243,'Exact published243parameterF32viscosity component required')
    for spec in [entry['original_receipt'],entry['original_configuration'],*entry['sources'],*entry['outputs'].values(),*entry['inputs'].values(),protocol['original_probe']]:
        observed_file(ROOT,spec['path'],spec)
    receipt = read(ROOT/entry['original_receipt']['path'])
    history = read(ROOT/entry['outputs']['history.json']['path'])
    inventory,_ = selected_inventory(receipt,history,entry['outputs']['weights.npz']['sha256'])
    require(inventory == entry['selected_inventory'],'Original selected viscosity inventory changed')
    output = ROOT/protocol['output_root']/f'phase-{phase}'
    require(output.is_relative_to(RUN) and not output.exists(),'Fresh original component phase required;no retry')
    os.sched_setaffinity(0,{protocol['host_cpu']})
    output.mkdir(parents=True)
    result = dict(status='starting_original_viscosity_GPU_phase',pid=os.getpid(),created_unix=time.time(),phase=phase,
        protocol=binding(protocol_path),fit_item_id=entry['fit_item_id'],rows=[],resource_observations=[],
        inference_device='cuda',timing_units='ms/local_viscosity_request',physical_simulation_steps=0,
        tensor_spatial_shape=[13,13,13],native_counts_xyz=[12,12,12],cells_per_metre=None,fluid_density_kg_m3=None,input_dt_s=None,
        physical_metadata_reason='Dimensionless local operator teacher;no physical time advance. Padding is not a13cell physical domain.',
        new_parameter_updates=0,new_reference_generation=False,independent_holdout=False,reference_or_mask_forwarded=False,
        primary_forward_observer_enabled=False,full_portfolio_complete=False)
    save(output/'result.json',result)
    observer = None
    started = time.monotonic()
    try:
        import numpy as np
        import torch
        from component_error_metrics import masked_errors
        torch.set_num_threads(1);torch.set_num_interop_threads(1)
        torch.use_deterministic_algorithms(True)
        torch.backends.cuda.matmul.allow_tf32 = False
        torch.backends.cudnn.allow_tf32 = False
        torch.backends.cudnn.benchmark = False
        require(torch.cuda.is_available() and torch.cuda.get_device_name() == protocol['expected_GPU'],'Registered real CUDA GPU required')
        observer = CUDAForwardObserver(torch)
        observer.enable('construction')
        source = next(spec for spec in entry['sources'] if spec['original_name'] == 'viscosity_calibration_model.py')
        spec = importlib.util.spec_from_file_location('original_viscosity_component',ROOT/source['path'])
        module = importlib.util.module_from_spec(spec)
        sys.modules[spec.name] = module
        with torch.device('cuda'):
            spec.loader.exec_module(module)
            network = module.ViscosityNet().to('cuda').eval()
        architecture = repr(network)
        with np.load(ROOT/entry['outputs']['weights.npz']['path'],allow_pickle=False) as weights:
            require(set(weights.files) == set(network.state_dict()) == set(inventory),'Exact complete published viscosity tensors required')
            loaded = {}
            weight_l1 = 0.
            for name in weights.files:
                array = weights[name]
                require(array.dtype.str == inventory[name]['dtype'] == '<f4' and list(array.shape) == inventory[name]['shape']
                        and digest(array) == inventory[name]['sha256'],'Original learned viscosity tensor differs')
                loaded[name] = torch.from_numpy(array.copy()).to('cuda')
                weight_l1 = max(weight_l1,float(np.abs(array.astype('<f8')).reshape(array.shape[0],-1).sum(axis=1).max()))
            network.load_state_dict(loaded,strict=True)

        def check_inventory():
            require(repr(network) == architecture,'Viscosity architecture changed')
            for name,value in network.state_dict().items():
                require(value.device.type == 'cuda' and value.dtype == torch.float32
                        and digest(value.detach().cpu().numpy()) == inventory[name]['sha256'],
                        'Original publishedF32viscosity tensors changed')

        check_inventory()
        manifest = read(ROOT/entry['inputs']['teacher_manifest']['path'])
        require(manifest['status'] == 'native_qualified' and manifest['counts_xyz'] == [12,12,12]
                and manifest['train_indices'] == list(range(64)) and manifest['development_indices'] == list(range(64,80))
                and manifest['archive_sha256'] == entry['inputs']['teacher']['sha256'],'Original teacher identity/split changed')
        with np.load(ROOT/entry['inputs']['teacher']['path'],allow_pickle=False) as archive:
            require(set(archive.files) == set(manifest['inventory']) == {'velocity','target','mask'},'Exact teacher fields required')
            arrays = {name:archive[name].copy() for name in archive.files}
        for name,array in arrays.items():
            expected = manifest['inventory'][name]
            require(array.dtype.str == expected['dtype'] and list(array.shape) == expected['shape']
                    and digest(array) == expected['sha256'] and np.isfinite(array).all(),'Exact original teacher array bytes required')
        require(arrays['velocity'].shape == arrays['target'].shape == (80,3,13,13,13)
                and arrays['mask'].shape == (1,3,13,13,13),'Original component field/storage dimensions required')
        probe = np.load(ROOT/protocol['original_probe']['path'],allow_pickle=False)
        require(probe.dtype.str == '<f4' and probe.shape == (2,3,13,13,13),'Original saved CPUprobe shape/dtype differs')
        mask = arrays['mask'][0]
        previous = None
        if phase == 1:
            first_path = ROOT/protocol['output_root']/'phase-0/result.json'
            previous = read(first_path)
            require(previous['status'] == 'original_viscosity_GPU_phase_qualified' and not Path(f'/proc/{previous["pid"]}').exists(),
                    'Original qualified phase0must be terminal;no repeated archive')
            previous = {row['pattern_index']:row for row in previous['rows']}
        result.update(GPU=torch.cuda.get_device_name(),Torch_version=torch.__version__,CUDA_version=torch.version.cuda,
            host_cpu=protocol['host_cpu'],threads=torch.get_num_threads(),interop_threads=torch.get_num_interop_threads(),
            architecture=architecture,weights=entry['outputs']['weights.npz'],teacher=entry['inputs']['teacher'],teacher_manifest=entry['inputs']['teacher_manifest'],
            original_probe=protocol['original_probe'],input_arrays_sha256={name:digest(value) for name,value in arrays.items()},
            setup_wall_seconds=time.monotonic()-started)
        observer.set_phase('setup')
        predictions = {}
        # Only this callable is timed;labels,masks,hashes andscoring stay outside.
        def complete(native):
            require(native.dtype.str == '<f4' and native.shape == (3,13,13,13) and np.isfinite(native).all(),
                    'Owned finiteF32velocity input required')
            velocity = torch.from_numpy(np.ascontiguousarray(native))[None].to('cuda')
            value = network(velocity)
            require(value.device.type == 'cuda' and value.dtype == torch.float32 and value.shape == velocity.shape,
                    'Original CUDAF32stiffness output required')
            owned = value.detach().to('cpu',copy=True).numpy()[0]
            torch.cuda.synchronize()
            return owned

        with torch.inference_mode():
            for position,index in enumerate(range(80) if phase == 0 else reversed(range(80))):
                require(time.monotonic()-started < protocol['worker_deadline_seconds'],'Finite viscosity worker bound exceeded')
                if position%20 == 0:
                    observation = resources();result['resource_observations'].append(observation)
                    require(not observation['other_compute_pids'],'Competing GPUcompute observed;retain as contended')
                native = arrays['velocity'][index].copy()
                original_input_sha = digest(native)
                observer.set_phase('first_call')
                tick = time.perf_counter_ns();value = complete(native);first_ns = time.perf_counter_ns()-tick
                require(np.isfinite(value).all() and not np.shares_memory(value,native),'Finite independently owned component output required')
                expected_sha = digest(value)
                if previous:
                    require(expected_sha == previous[index]['output_sha256'],'Cross-process viscosity field hash differs')
                if phase == 0:
                    predictions[f'pattern{index:03d}'] = value.copy()
                values = masked_errors(value,arrays['target'][index],mask)
                probe_check = None
                if index < 2:
                    # Two FP3281term contractions can differ by at most2gamma81
                    # times max|input|andmax output-channel weightL1,plus underflow.
                    unit = float(np.finfo(np.float32).eps)/2
                    gamma = 81*unit/(1-81*unit)
                    bound = 2*gamma*float(np.abs(native).max())*weight_l1+float(np.finfo(np.float32).tiny)
                    difference = float(np.abs(value.astype('<f8')-probe[index].astype('<f8')).max())
                    require(difference <= bound,'Saved CPUprobe andCUDApublishedF32output differ beyond preregistered roundoff bound')
                    probe_check = dict(saved_CPU_probe_maximum_difference=difference,predeclared_absolute_roundoff_bound=bound,
                        CPU_probe_regenerated=False)

                def sample():
                    tick = time.perf_counter_ns();predicted = complete(native);elapsed = time.perf_counter_ns()-tick
                    require(elapsed > 0 and digest(predicted) == expected_sha and np.isfinite(predicted).all()
                            and not np.shares_memory(predicted,native),'Repeated finite owned output differs')
                    return elapsed

                observer.set_phase('warmup')
                warmups = [sample() for _ in range(protocol['warmups_per_case'])]
                before = dict(observer.calls)
                with observer.unobserved('primary'):
                    samples = [sample() for _ in range(protocol['samples_per_case'])]
                    require(observer.handle is None and dict(observer.calls) == before,'Primary incorrectly includes observer')
                pairs = []
                for number in range(protocol['calibration_pairs_per_case']):
                    order = ['on','off'] if (phase+index+number)%2 == 0 else ['off','on']
                    pair = dict(pair_index=number,order=order)
                    for mode in order:
                        if mode == 'on':
                            observer.set_phase('calibration_on');pair['on_ns'] = sample()
                        else:
                            with observer.unobserved('calibration_off'):
                                pair['off_ns'] = sample()
                    pair['on_minus_off_ns'] = pair['on_ns']-pair['off_ns'];pairs.append(pair)
                require(digest(native) == original_input_sha,'Caller velocity input mutated')
                result['rows'].append(dict(pattern_index=index,population='fitting' if index < 64 else 'consumed_development',
                    input_sha256=original_input_sha,target_sha256=digest(arrays['target'][index]),mask_sha256=digest(mask),
                    output_sha256=expected_sha,metrics=values,raw_wall_nanoseconds=samples,median_ms=statistics.median(samples)/1e6,
                    instrumented_first_call_ns=first_ns,instrumented_warmup_ns=warmups,calibration=pairs,original_CPU_probe_comparison=probe_check))
                require(torch.cuda.max_memory_allocated() <= protocol['maximum_CUDA_allocated_bytes']
                        and resource.getrusage(resource.RUSAGE_SELF).ru_maxrss*1024 <= protocol['maximum_RSS_bytes'],
                        'Viscosity worker resource bound exceeded')
            observation = resources();result['resource_observations'].append(observation)
            require(not observation['other_compute_pids'],'Other GPUcompute observed')
        require(all(digest(value) == result['input_arrays_sha256'][name] for name,value in arrays.items()),'Original teacher arrays changed')
        check_inventory()
        observer.close()
        require(observer.closed and not observer.forbidden_attempts,'CUDAobserver must close with no forbidden forwards')
        if phase == 0:
            archive = output/'component-predictions.npz'
            np.savez_compressed(archive,**predictions)
            result['prediction_archive'] = binding(archive)
        else:
            result['prediction_archive'] = read(ROOT/protocol['output_root']/'phase-0/result.json')['prediction_archive']
        verify_sources(protocol)
        from python_source_coverage import collect
        coverage = collect(sys.modules,ROOT)
        unbound = [name for name in coverage['lab_python'] if name not in protocol['source_sha256']]
        require(not unbound,'Actual imported component source absent from frozen protocol')
        result.update(status='original_viscosity_GPU_phase_qualified',finished_unix=time.time(),cases=80,
            device_observation=observer.evidence(),source_coverage=coverage,unbound_lab_modules=unbound,
            learned_tensors_and_architecture_unchanged=True,primary_observer_calls=0,
            primary_calls=80*protocol['samples_per_case'],calibration_pairs=80*protocol['calibration_pairs_per_case'],
            logical_calls=80*(1+protocol['warmups_per_case']+protocol['samples_per_case']+2*protocol['calibration_pairs_per_case']),
            peak_CUDA_allocated_bytes=torch.cuda.max_memory_allocated(),peak_RSS_bytes=resource.getrusage(resource.RUSAGE_SELF).ru_maxrss*1024,
            elapsed_wall_seconds=time.monotonic()-started)
    except BaseException as error:
        result.update(status='original_viscosity_GPU_adapter_gap',error_type=type(error).__name__,error=str(error),
            device_observation=observer.evidence() if observer else None,scientific_accuracy_failure_claim=False)
        raise
    finally:
        if observer:
            observer.close()
        save(output/'result.json',result)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--protocol',type=Path,required=True)
    parser.add_argument('--phase',type=int,choices=(0,1),required=True)
    args = parser.parse_args()
    run(args.protocol.resolve(),args.phase)
